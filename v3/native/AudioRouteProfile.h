#pragma once
#include <cstdint>
#include <cstring>

namespace CDV3AudioProfiles {
struct Profile {
    const char *name;
    uint8_t uuid[16];
    uint32_t subtype;
    uint64_t text, setter, flag;
    uint8_t prologue[16];
};
// New profile: exact 20A357 MediaExperience image, SHA-256 recorded in the
// compatibility research manifest. The four setter instructions directly
// establish the target byte: ADRP + ADD + STRB w0 + RET. These are unslid VAs.
inline constexpr Profile Profiles[]={
    {"ios16.6-arm64",{0x17,0x90,0xdb,0xae,0x04,0xb6,0x32,0xb7,0xb5,0xe7,0xaa,0x39,0xe5,0x71,0xb2,0x08},0,
     0x1959c6000ULL,0x195a6450cULL,0x1dd3753e0ULL,
     {0x88,0xc8,0x23,0xb0,0x08,0x21,0x07,0x91,0x00,0x61,0x08,0x39,0xc0,0x03,0x5f,0xd6}},
    {"ios16.0-20A357-arm64e",{0xf9,0x44,0x81,0x7f,0x4a,0x89,0x31,0xee,0xa4,0xf6,0x0d,0xa7,0x74,0x9d,0x2d,0xac},0x80000002,
     0x196468000ULL,0x196516c50ULL,0x1da661cb8ULL,
     {0x48,0x0a,0x22,0xf0,0x08,0x81,0x2a,0x91,0x00,0x61,0x08,0x39,0xc0,0x03,0x5f,0xd6}}
};
inline const Profile *Find(const uint8_t *uuid,uint32_t type,uint32_t subtype) {
    if(!uuid || type!=0x100000c)return nullptr;
    for(const auto &profile:Profiles)
        if(subtype==profile.subtype && !memcmp(uuid,profile.uuid,16))return &profile;
    return nullptr;
}
}
