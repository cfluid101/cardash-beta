// Layouts describe only the fields this adapter accesses. Exact image identity
// remains required: 17.0 and 17.6.1 have equal entry prefixes but different fields.
enum class LayoutFamily { Middle, RequestIdentifier, EarlyUnsupported };
struct Layout {
    size_t hostTime,selectedTransport,selectedInterface,stateSize,requestIdentifier;
};
static constexpr Layout LayoutFor(LayoutFamily family) {
    return family==LayoutFamily::RequestIdentifier ? Layout{0xb8,0xc0,0xd0,0xd8,0xb0} :
           family==LayoutFamily::EarlyUnsupported ? Layout{0xb0,0,0xc0,0xc8,0} :
                                                   Layout{0xb0,0xb8,0xc8,0xd0,0};
}
static constexpr const char *LayoutName(LayoutFamily family) {
    return family==LayoutFamily::RequestIdentifier ? "request-identifier" :
           family==LayoutFamily::EarlyUnsupported ? "early-usb-release-unimplemented" : "middle";
}
struct Profile {
    const char *name;
    uint8_t uuid[16];
    uint32_t cpuType, cpuSubtype;
    size_t updateOffset, eventOffset, prologueSize;
    uint8_t updateBytes[20], eventBytes[20];
    bool guardedLayout;
    LayoutFamily layout=LayoutFamily::Middle;
};

